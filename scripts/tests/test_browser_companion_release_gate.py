from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import pytest
from tripchord.agents.companion_control_tools import (
    COMPANION_RELEASE_SEAL_RELATIVE_PATH,
    CompanionControlToolError,
    companion_release_seal_bytes,
    verified_companion_build_identity,
)

from scripts import browser_companion_release_gate as release_gate

BUILD_ALLOWLIST = (
    "manifest.json",
    "popup.html",
    "popup.css",
    "popup.js",
    "offscreen.html",
    "src/background.js",
    "src/content.js",
    "src/offscreen.js",
    "src/parser.js",
)


def _build_sha256(companion: Path) -> str:
    digest = hashlib.sha256()
    for relative_path in BUILD_ALLOWLIST:
        payload = (companion / relative_path).read_bytes()
        digest.update(relative_path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(str(len(payload)).encode("ascii"))
        digest.update(b"\0")
        digest.update(payload)
        digest.update(b"\0")
    return digest.hexdigest()


def _write_repository_fixture(repository: Path) -> tuple[Path, str]:
    companion = repository / "apps" / "browser-companion"
    (companion / "src").mkdir(parents=True)
    payloads = {
        "manifest.json": json.dumps({"version": "9.8.7"}),
        "popup.html": "popup html",
        "popup.css": "popup css",
        "popup.js": "popup js",
        "offscreen.html": "offscreen html",
        "src/background.js": 'const CONTENT_RUNTIME_VERSION = "fixture-runtime-1";',
        "src/content.js": "content js",
        "src/offscreen.js": "offscreen js",
        "src/parser.js": "parser js",
    }
    for relative_path, payload in payloads.items():
        path = companion / relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(payload, encoding="utf-8")
    build_sha256 = _build_sha256(companion)
    identity = {
        "protocol_version": "tripchord-companion-control-v1",
        "manifest_version": "9.8.7",
        "build_sha256": build_sha256,
        "content_runtime_version": "fixture-runtime-1",
    }
    (companion / "src" / "build-meta.js").write_text(
        "// Generated by scripts/update-build-meta.mjs. Do not edit by hand.\n"
        "globalThis.TRIPCHORD_COMPANION_BUILD_META = "
        f"Object.freeze({json.dumps(identity, indent=2)});\n",
        encoding="utf-8",
    )
    seal_path = companion / COMPANION_RELEASE_SEAL_RELATIVE_PATH
    seal_path.write_bytes(companion_release_seal_bytes(companion))
    seal_path.chmod(0o600)
    return companion, build_sha256


def test_gate_accepts_exact_current_build_metadata(tmp_path: Path) -> None:
    _, build_sha256 = _write_repository_fixture(tmp_path)

    assert release_gate.verify_build_metadata(tmp_path) == build_sha256


def test_gate_fails_closed_on_stale_metadata_before_running_contracts(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    companion, _ = _write_repository_fixture(tmp_path)
    metadata_path = companion / "src" / "build-meta.js"
    metadata_before = metadata_path.read_bytes()
    (companion / "popup.css").write_text("changed after metadata generation", encoding="utf-8")
    launched: list[str] = []

    def unexpected_run(*args: object, **kwargs: object) -> None:
        del args, kwargs
        launched.append("subprocess")

    monkeypatch.setattr(release_gate, "_run_checked", unexpected_run)

    with pytest.raises(release_gate.ReleaseGateError, match="发布 seal 无效"):
        release_gate.run_release_gate(repository=tmp_path)

    assert launched == []
    assert metadata_path.read_bytes() == metadata_before


def test_gate_rejects_runtime_version_mismatch(tmp_path: Path) -> None:
    companion, _ = _write_repository_fixture(tmp_path)
    metadata_path = companion / "src" / "build-meta.js"
    metadata_path.write_text(
        metadata_path.read_text(encoding="utf-8").replace(
            '"content_runtime_version": "fixture-runtime-1"',
            '"content_runtime_version": "fixture-runtime-wrong"',
        ),
        encoding="utf-8",
    )

    with pytest.raises(release_gate.ReleaseGateError, match="runtime version"):
        release_gate.verify_build_metadata(tmp_path)


