def _repository() -> Path:
    return Path(__file__).resolve().parents[1]


def _canonical_bytes(value: object) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def _canonical_sha256(value: object) -> str:
    return hashlib.sha256(_canonical_bytes(value)).hexdigest()


def _file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _mapping(value: object, label: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise EvidenceCaptureError(f"{label} must be an object")
    return value


def _sequence(value: object, label: str) -> Sequence[Any]:
    if not isinstance(value, list | tuple):
        raise EvidenceCaptureError(f"{label} must be an array")
    return value


def _string(value: object, label: str, *, maximum: int = 512) -> str:
    if not isinstance(value, str) or not value or len(value) > maximum:
        raise EvidenceCaptureError(f"{label} must be a non-empty bounded string")
    return value


def _optional_string(value: object, label: str, *, maximum: int = 512) -> str | None:
    if value is None:
        return None
    return _string(value, label, maximum=maximum)


def _boolean(value: object, label: str) -> bool:
    if not isinstance(value, bool):
        raise EvidenceCaptureError(f"{label} must be boolean")
    return value


def _integer(value: object, label: str, *, minimum: int = 0) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise EvidenceCaptureError(f"{label} must be an integer >= {minimum}")
    return value


def _digest(value: object, label: str) -> str:
    normalized = _string(value, label, maximum=64).lower()
    if not _SHA256.fullmatch(normalized):
        raise EvidenceCaptureError(f"{label} must be a lowercase SHA-256 digest")
    return normalized


def _decimal_text(value: object, label: str) -> str:
    if isinstance(value, bool) or not isinstance(value, int | float | str):
        raise EvidenceCaptureError(f"{label} must be numeric")
    try:
        amount = Decimal(str(value))
    except InvalidOperation as exc:
        raise EvidenceCaptureError(f"{label} must be numeric") from exc
    if not amount.is_finite() or amount < 0:
        raise EvidenceCaptureError(f"{label} must be a non-negative finite amount")
    normalized = format(amount, "f")
    if "." in normalized:
        normalized = normalized.rstrip("0").rstrip(".")
    return normalized or "0"


def _validate_base_url(value: str) -> str:
    parsed = urlsplit(value)
    if (
        parsed.scheme != "http"
        or parsed.hostname not in {"127.0.0.1", "localhost", "::1"}
        or parsed.username is not None
        or parsed.password is not None
        or parsed.query
        or parsed.fragment
        or parsed.path not in {"", "/"}
    ):
        raise EvidenceCaptureError("base URL must be a plain loopback HTTP origin")
    return value.rstrip("/")


def _secure_token(path: Path) -> str:
    try:
        file_stat = path.lstat()
    except FileNotFoundError as exc:
        raise EvidenceCaptureError("bridge token file does not exist") from exc
    if stat.S_ISLNK(file_stat.st_mode) or not stat.S_ISREG(file_stat.st_mode):
        raise EvidenceCaptureError("bridge token path must be a regular file, not a symlink")
    if file_stat.st_uid != os.getuid() or stat.S_IMODE(file_stat.st_mode) != 0o600:
        raise EvidenceCaptureError("bridge token file must be owned by this user with mode 0600")
    if file_stat.st_size > 4096:
        raise EvidenceCaptureError("bridge token file is unexpectedly large")
    token = path.read_text(encoding="utf-8").strip()
    if not 32 <= len(token) <= 256 or any(character.isspace() for character in token):
        raise EvidenceCaptureError("bridge token file contains an invalid token shape")
    return token


def _fetch_json(
    client: httpx.Client,
    path: str,
    *,
    bridge_token: str | None = None,
) -> dict[str, Any]:
    headers = {BRIDGE_TOKEN_HEADER: bridge_token} if bridge_token is not None else None
    try:
        response = client.get(path, headers=headers)
    except httpx.HTTPError as exc:
        raise EvidenceCaptureError(f"read-only GET failed for {path}") from exc
    if response.is_redirect:
        raise EvidenceCaptureError(f"read-only GET refused a redirect for {path}")
    if response.status_code != 200:
        raise EvidenceCaptureError(
            f"read-only GET returned HTTP {response.status_code} for {path}"
        )
    try:
        payload = response.json()
    except ValueError as exc:
        raise EvidenceCaptureError(f"read-only GET returned invalid JSON for {path}") from exc
    if not isinstance(payload, dict):
        raise EvidenceCaptureError(f"read-only GET returned a non-object for {path}")
    return payload


def _normalize_query(raw: object) -> dict[str, object]:
    query = _mapping(raw, "task.query")
    options = _mapping(query.get("options", {}), "task.query.options")
    allowed_options = {
        "segment",
        "expected_package_area",
        "expected_lodging_place_key",
        "__tripchord_allow_recent_quote_reuse",
    }
    unexpected = set(options) - allowed_options
    if unexpected:
        raise EvidenceCaptureError(f"task.query.options has unsealed fields: {sorted(unexpected)}")
    return {
        "destination": _string(query.get("destination"), "task.query.destination"),
        "start_date": _string(query.get("start_date"), "task.query.start_date", maximum=10),
        "end_date": _string(query.get("end_date"), "task.query.end_date", maximum=10),
        "adults": _integer(query.get("adults"), "task.query.adults", minimum=1),
        "rooms": _integer(query.get("rooms"), "task.query.rooms", minimum=1),
        "currency": _string(query.get("currency"), "task.query.currency", maximum=3).upper(),
        "segment": _string(options.get("segment"), "task.query.options.segment"),
        "expected_package_area": _string(
            options.get("expected_package_area"),
            "task.query.options.expected_package_area",
        ),
        "expected_lodging_place_key": _string(
            options.get("expected_lodging_place_key"),
            "task.query.options.expected_lodging_place_key",
        ),
        "recent_quote_reuse_allowed": _boolean(
            options.get("__tripchord_allow_recent_quote_reuse"),
            "task.query.options.__tripchord_allow_recent_quote_reuse",
        ),
    }


def _provider_host_allowed(provider: str, host: str) -> bool:
    return any(
        host == domain or host.endswith(f".{domain}")
        for domain in _PROVIDER_DOMAINS.get(provider, ())
    )


def _sanitize_page_url(raw: object, provider: str, label: str) -> str:
    value = _string(raw, label, maximum=4096)
    parsed = urlsplit(value)
    host = (parsed.hostname or "").lower()
    if (
        parsed.scheme != "https"
        or not _provider_host_allowed(provider, host)
        or parsed.username is not None
        or parsed.password is not None
    ):
        raise EvidenceCaptureError(f"{label} is not an allowed provider HTTPS URL")
    safe_keys = _SAFE_URL_QUERY_KEYS[provider]
    safe_query: list[tuple[str, str]] = []
    for key, item in parse_qsl(parsed.query, keep_blank_values=True):
        if key.lower() in safe_keys and len(key) <= 64 and len(item) <= 256:
            safe_query.append((key, item))
    safe_query.sort(key=lambda pair: (pair[0].lower(), pair[0], pair[1]))
    return urlunsplit(
        (
            "https",
            host,
            parsed.path or "/",
            urlencode(safe_query, doseq=True),
            "",
        )
    )


def _normalize_quote(raw: object, provider: str) -> dict[str, object]:
    quote_payload = _mapping(raw, "task.quote")
    quote_provider = _string(quote_payload.get("provider"), "task.quote.provider")
    if quote_provider != provider:
        raise EvidenceCaptureError("task quote provider does not match its source task")
    kind = _string(quote_payload.get("kind"), "task.quote.kind")
    if kind != "lodging":
        raise EvidenceCaptureError("focused lodging evidence cannot contain non-lodging quotes")
    details = _mapping(quote_payload.get("details"), "task.quote.details")
    property_id = _string(
        details.get("property_id"), "task.quote.details.property_id", maximum=128
    )
    property_name = _string(
        details.get("property_name"), "task.quote.details.property_name", maximum=256
    )
    taxes = quote_payload.get("taxes_included")
    if taxes is not None and not isinstance(taxes, bool):
        raise EvidenceCaptureError("task.quote.taxes_included must be boolean or null")
    return {
        "provider": quote_provider,
        "kind": kind,
        "page_url": _sanitize_page_url(
            quote_payload.get("page_url"), provider, "task.quote.page_url"
        ),
        "captured_at": _string(
            quote_payload.get("captured_at"), "task.quote.captured_at", maximum=40
        ),
        "evidence_sha256": _digest(
            quote_payload.get("evidence_sha256"), "task.quote.evidence_sha256"
        ),
        "parser_version": _string(
            quote_payload.get("parser_version"), "task.quote.parser_version", maximum=64
        ),
        "amount": _decimal_text(quote_payload.get("amount"), "task.quote.amount"),
        "currency": _string(
            quote_payload.get("currency"), "task.quote.currency", maximum=3
        ).upper(),
        "price_basis": _string(
            quote_payload.get("price_basis"), "task.quote.price_basis", maximum=32
        ),
        "taxes_included": taxes,
        "price_finality": _string(
            details.get("price_finality"), "task.quote.details.price_finality", maximum=64
        ),
        "availability": _string(
            details.get("availability"), "task.quote.details.availability", maximum=64
        ),
        "property": {"id": property_id, "name": property_name},
    }


def _normalize_url_shape(raw: object, label: str) -> dict[str, object]:
    shape = _mapping(raw, label)
    host = _string(shape.get("host"), f"{label}.host", maximum=255).lower()
    if not _provider_host_allowed("qunar", host):
        raise EvidenceCaptureError(f"{label}.host is outside the Qunar domain boundary")
    query_keys = [
        _string(item, f"{label}.query_keys[]", maximum=64)
        for item in _sequence(shape.get("query_keys", []), f"{label}.query_keys")
    ]
    if len(query_keys) > 16:
        raise EvidenceCaptureError(f"{label}.query_keys exceeds the bounded diagnostic")
    return {
        "parseable": _boolean(shape.get("parseable"), f"{label}.parseable"),
        "scheme": _string(shape.get("scheme"), f"{label}.scheme", maximum=8),
        "host": host,
        "path_shape": _string(
            shape.get("path_shape"), f"{label}.path_shape", maximum=512
        ),
        "query_keys": query_keys,
        "query_keys_truncated": _boolean(
            shape.get("query_keys_truncated"), f"{label}.query_keys_truncated"
        ),
        "has_fragment": _boolean(shape.get("has_fragment"), f"{label}.has_fragment"),
    }


def _normalize_navigation_diagnostic(raw: object) -> dict[str, object]:
    diagnostic = _mapping(raw, "failure.details.navigation_diagnostic")
    trace: list[dict[str, object]] = []
    for index, item in enumerate(
        _sequence(
            diagnostic.get("redirect_trace", []),
            "failure.details.navigation_diagnostic.redirect_trace",
        )
    ):
        if index >= 8:
            raise EvidenceCaptureError("Qunar redirect trace exceeds eight bounded entries")
        entry = _mapping(item, f"failure.redirect_trace[{index}]")
        status_value = entry.get("status")
        trace.append(
            {
                "sequence": _integer(entry.get("sequence"), f"redirect_trace[{index}].sequence"),
                "phase": _string(entry.get("phase"), f"redirect_trace[{index}].phase"),
                "tab_role": _string(entry.get("tab_role"), f"redirect_trace[{index}].tab_role"),
                "status": _optional_string(
                    status_value, f"redirect_trace[{index}].status", maximum=64
                ),
                "transient": _boolean(
                    entry.get("transient"), f"redirect_trace[{index}].transient"
                ),
                "url": _normalize_url_shape(entry.get("url"), f"redirect_trace[{index}].url"),
            }
        )
    return {
        "provider": _string(diagnostic.get("provider"), "navigation.provider"),
        "vertical": _string(diagnostic.get("vertical"), "navigation.vertical"),
        "stage": _string(diagnostic.get("stage"), "navigation.stage"),
        "reason": _string(diagnostic.get("reason"), "navigation.reason"),
        "rejected_url": _normalize_url_shape(
            diagnostic.get("rejected_url"), "navigation.rejected_url"
        ),
        "login_return_url": _normalize_url_shape(
            diagnostic.get("login_return_url"), "navigation.login_return_url"
        ),
        "redirect_trace": trace,
    }


def _normalize_browser_isolation(raw: object) -> dict[str, object]:
    isolation = _mapping(raw, "failure.details.browser_isolation")
    string_fields = (
        "scope",
        "owner",
        "window_type",
        "requested_window_state",
        "cleanup_policy",
        "fallback_policy",
        "lifecycle_state",
        "observed_window_state",
    )
    boolean_fields = (
        "requested_focused",
        "tab_active_in_isolated_window",
        "reused_user_window",
        "minimized",
        "observed_focused",
    )
    result: dict[str, object] = {
        field: _string(isolation.get(field), f"browser_isolation.{field}")
        for field in string_fields
    }
    result.update(
        {
            field: _boolean(isolation.get(field), f"browser_isolation.{field}")
            for field in boolean_fields
        }
    )
    result["observed_active_tab_count"] = _integer(
        isolation.get("observed_active_tab_count"),
        "browser_isolation.observed_active_tab_count",
    )
    return result


