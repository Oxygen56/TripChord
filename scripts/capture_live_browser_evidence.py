def _normalize_task(raw: object, expected_task_id: str) -> dict[str, object]:
    task = _mapping(raw, f"task[{expected_task_id}]")
    task_id = _string(task.get("id"), "task.id", maximum=160)
    if task_id != expected_task_id or not _TASK_ID.fullmatch(task_id):
        raise EvidenceCaptureError("bridge returned an unexpected task ID")
    provider = _string(task.get("provider"), "task.provider", maximum=32)
    if provider not in _PROVIDER_DOMAINS:
        raise EvidenceCaptureError("focused evidence contains an unsupported provider")
    kind = _string(task.get("kind"), "task.kind", maximum=32)
    if kind != "lodging":
        raise EvidenceCaptureError("focused evidence only accepts lodging tasks")
    state = _string(task.get("state"), "task.state", maximum=32)
    if state not in {"succeeded", "blocked", "failed", "cancelled"}:
        raise EvidenceCaptureError("focused evidence requires terminal bridge tasks")
    quotes = [
        _normalize_quote(item, provider)
        for item in _sequence(task.get("quotes", []), "task.quotes")
    ]
    quotes.sort(
        key=lambda quote_item: (
            str(_mapping(quote_item["property"], "quote.property")["id"]),
            Decimal(str(quote_item["amount"])),
            str(quote_item["evidence_sha256"]),
        )
    )
    failure_raw = task.get("failure")
    failure = _normalize_failure(failure_raw, provider) if failure_raw is not None else None
    if state == "succeeded" and (not quotes or failure is not None):
        raise EvidenceCaptureError("successful task must have quotes and no failure")
    if state != "succeeded" and (quotes or failure is None):
        raise EvidenceCaptureError("non-success terminal task must have one failure and no quotes")
    reused = task.get("reused_from_task_id")
    return {
        "task_id": task_id,
        "provider": provider,
        "kind": kind,
        "query": _normalize_query(task.get("query")),
        "state": state,
        "created_at": _string(task.get("created_at"), "task.created_at", maximum=40),
        "updated_at": _string(task.get("updated_at"), "task.updated_at", maximum=40),
        "attempt_count": _integer(task.get("attempt_count"), "task.attempt_count"),
        "reused_from_task_id": _optional_string(
            reused, "task.reused_from_task_id", maximum=160
        ),
        "inflight_coalesced": _boolean(
            task.get("inflight_coalesced"), "task.inflight_coalesced"
        ),
        "quote_count": len(quotes),
        "quotes": quotes,
        "failure": failure,
    }


