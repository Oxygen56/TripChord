def _normalize_source_artifacts(
    raw: Sequence[Mapping[str, str]],
) -> list[dict[str, str]]:
    normalized: list[dict[str, str]] = []
    seen: set[str] = set()
    for index, item in enumerate(raw):
        path = _string(item.get("path"), f"source_artifacts[{index}].path", maximum=512)
        candidate = Path(path)
        if candidate.is_absolute() or ".." in candidate.parts or path in seen:
            raise EvidenceCaptureError("source artifact paths must be unique repository paths")
        seen.add(path)
        normalized.append(
            {
                "path": path,
                "sha256": _digest(
                    item.get("sha256"), f"source_artifacts[{index}].sha256"
                ),
            }
        )
    if not normalized:
        raise EvidenceCaptureError("sealed evidence requires source artifact hashes")
    normalized.sort(key=lambda item: item["path"])
    return normalized


