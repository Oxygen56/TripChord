def build_sealed_evidence(
    *,
    task_payloads: Sequence[Mapping[str, Any]],
    task_ids: Sequence[str],
    companion_payload: Mapping[str, Any],
    companion_id: str | None,
    runtime_payload: Mapping[str, Any],
    source_summary: Mapping[str, Any] | None,
    source_artifacts: Sequence[Mapping[str, str]],
    release_binding: Mapping[str, object],
    scope_decisions: Sequence[Mapping[str, object]] = (),
) -> dict[str, object]:
    if len(task_payloads) != len(task_ids) or len(task_ids) < 2:
        raise EvidenceCaptureError("focused evidence requires at least two exact task IDs")
    if len(set(task_ids)) != len(task_ids):
        raise EvidenceCaptureError("focused evidence task IDs must be unique")
    sources = [
        _normalize_task(payload, task_id)
        for payload, task_id in zip(task_payloads, task_ids, strict=True)
    ]
    sources.sort(key=lambda item: (str(item["provider"]), str(item["task_id"])))
    query = _mapping(sources[0]["query"], "source query")
    if any(source["query"] != query for source in sources[1:]):
        raise EvidenceCaptureError("focused source tasks do not share one exact query")
    companion = _normalize_companion(companion_payload, companion_id)
    runtime = _normalize_runtime(runtime_payload)
    _validate_runtime_binding(sources, companion, runtime, release_binding)
    source_summary_assessment = (
        _mapping(source_summary.get("assessment"), "source summary.assessment")
        if source_summary is not None
        else {}
    )
    assessment = _derive_assessment(
        sources,
        publication_gate_attempted=(
            _boolean(
                source_summary_assessment.get("publication_gate_attempted"),
                "source summary assessment.publication_gate_attempted",
            )
            if source_summary is not None
            else False
        ),
        publication_gate_passed=(
            _boolean(
                source_summary_assessment.get("publication_gate_passed"),
                "source summary assessment.publication_gate_passed",
            )
            if source_summary is not None
            else False
        ),
    )
    normalized_source_artifacts = _normalize_source_artifacts(source_artifacts)
    summary_scope_decisions = (
        _summary_scope_decisions(source_summary) if source_summary is not None else []
    )
    normalized_scope_decisions = _normalize_scope_decisions(
        [*summary_scope_decisions, *scope_decisions]
    )
    if source_summary is not None:
        _validate_source_summary(source_summary, sources, query, companion, runtime, assessment)
    artifact: dict[str, object] = {
        "schema_version": SCHEMA_VERSION,
        "evidence_closed_at": max(str(source["updated_at"]) for source in sources),
        "scope": "background_read_only_lodging_canary",
        "collection_contract": {
            "http_methods": ["GET"],
            "new_browser_tasks_submitted": False,
            "browser_interaction_performed": False,
            "model_calls_performed": False,
            "raw_page_text_persisted": False,
            "credentials_persisted": False,
            "url_policy": (
                "provider HTTPS URL with semantic query allowlist; tracking values removed"
            ),
        },
        "query": dict(query),
        "runtime": runtime,
        "companion": companion,
        "release_binding": dict(release_binding),
        "source_tasks": sources,
        "scope_decisions": normalized_scope_decisions,
        "derived_assessment": assessment,
        "source_artifacts": normalized_source_artifacts,
        "claim_boundary": _claim_boundary(companion, assessment),
        "integrity": {
            "canonicalization": CANONICALIZATION,
            "task_snapshot_sha256": {
                str(source["task_id"]): _canonical_sha256(source) for source in sources
            },
            "companion_snapshot_sha256": _canonical_sha256(companion),
            "runtime_snapshot_sha256": _canonical_sha256(runtime),
        },
    }
    integrity_payload = dict(_mapping(artifact["integrity"], "artifact.integrity"))
    integrity_payload["input_sha256"] = _canonical_sha256(_input_payload(artifact))
    artifact["integrity"] = integrity_payload
    unsigned = copy.deepcopy(artifact)
    integrity_payload["result_sha256"] = _canonical_sha256(unsigned)
    _assert_public_safe(artifact)
    verify_sealed_evidence(artifact)
    return artifact


def verify_sealed_evidence(raw: object) -> None:
    artifact = _mapping(raw, "sealed artifact")
    if artifact.get("schema_version") != SCHEMA_VERSION:
        raise EvidenceCaptureError("sealed artifact has an unexpected schema version")
    integrity = _mapping(artifact.get("integrity"), "sealed artifact.integrity")
    if integrity.get("canonicalization") != CANONICALIZATION:
        raise EvidenceCaptureError("sealed artifact canonicalization is unsupported")
    source_tasks = [
        _mapping(item, "sealed source task")
        for item in _sequence(artifact.get("source_tasks"), "sealed source tasks")
    ]
    task_hashes = _mapping(
        integrity.get("task_snapshot_sha256"), "integrity.task_snapshot_sha256"
    )
    expected_task_hashes = {
        str(source["task_id"]): _canonical_sha256(source) for source in source_tasks
    }
    if dict(task_hashes) != expected_task_hashes:
        raise EvidenceCaptureError("sealed task snapshot digest mismatch")
    if integrity.get("companion_snapshot_sha256") != _canonical_sha256(
        artifact.get("companion")
    ):
        raise EvidenceCaptureError("sealed Companion snapshot digest mismatch")
    if integrity.get("runtime_snapshot_sha256") != _canonical_sha256(artifact.get("runtime")):
        raise EvidenceCaptureError("sealed runtime snapshot digest mismatch")
    if integrity.get("input_sha256") != _canonical_sha256(_input_payload(artifact)):
        raise EvidenceCaptureError("sealed input digest mismatch")
    old_assessment = _mapping(
        artifact.get("derived_assessment"), "sealed artifact.derived_assessment"
    )
    recomputed = _derive_assessment(
        source_tasks,
        publication_gate_attempted=_boolean(
            old_assessment.get("publication_gate_attempted"),
            "derived assessment.publication_gate_attempted",
        ),
        publication_gate_passed=_boolean(
            old_assessment.get("publication_gate_passed"),
            "derived assessment.publication_gate_passed",
        ),
    )
    if dict(old_assessment) != recomputed:
        raise EvidenceCaptureError("sealed derived assessment is not reproducible")
    unsigned = copy.deepcopy(dict(artifact))
    unsigned_integrity = dict(_mapping(unsigned.get("integrity"), "sealed integrity"))
    result_sha256 = unsigned_integrity.pop("result_sha256", None)
    unsigned["integrity"] = unsigned_integrity
    if result_sha256 != _canonical_sha256(unsigned):
        raise EvidenceCaptureError("sealed result digest mismatch")
    _assert_public_safe(artifact)


def _fsync_directory(directory: Path) -> None:
    flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0)
    descriptor = os.open(directory, flags)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def build_run_summary(
    raw: object,
    *,
    sealed_artifact_name: str,
) -> dict[str, object]:
    verify_sealed_evidence(raw)
    artifact = _mapping(raw, "sealed artifact")
    runtime = _mapping(artifact["runtime"], "sealed runtime")
    companion = _mapping(artifact["companion"], "sealed companion")
    identity = _mapping(companion["build_identity"], "sealed build identity")
    assessment = _mapping(artifact["derived_assessment"], "sealed assessment")
    lowest_by_provider = _mapping(
        assessment["lowest_exact_all_in_rate_by_provider"],
        "sealed lowest rates",
    )
    sources: list[dict[str, object]] = []
    for raw_source in _sequence(artifact["source_tasks"], "sealed source tasks"):
        source = _mapping(raw_source, "sealed source task")
        item: dict[str, object] = {
            "task_id": source["task_id"],
            "provider": source["provider"],
            "state": source["state"],
            "attempt_count": source["attempt_count"],
            "quote_count": source["quote_count"],
        }
        lowest = lowest_by_provider.get(str(source["provider"]))
        if lowest is not None:
            lowest_rate = _mapping(lowest, "sealed lowest provider rate")
            property_identity = _mapping(
                lowest_rate["property"], "sealed lowest property"
            )
            item["lowest_audited_rate"] = {
                "amount": lowest_rate["amount"],
                "currency": lowest_rate["currency"],
                "price_basis": lowest_rate["price_basis"],
                "taxes_included": lowest_rate["taxes_included"],
                "price_finality": lowest_rate["price_finality"],
                "property_id": property_identity["id"],
                "property_name": property_identity["name"],
                "evidence_sha256": lowest_rate["evidence_sha256"],
            }
        failure_raw = source.get("failure")
        if failure_raw is not None:
            failure = _mapping(failure_raw, "sealed failure")
            failure_summary: dict[str, object] = {
                "code": failure["code"],
                "retryable": failure["retryable"],
            }
            navigation_raw = failure.get("navigation_diagnostic")
            if navigation_raw is not None:
                navigation = _mapping(navigation_raw, "sealed navigation")
                rejected = _mapping(navigation["rejected_url"], "sealed rejected URL")
                returned = _mapping(
                    navigation["login_return_url"], "sealed login return URL"
                )
                failure_summary.update(
                    {
                        "reason": navigation["reason"],
                        "redirect_host": rejected["host"],
                        "redirect_path_shape": rejected["path_shape"],
                        "login_return_host": returned["host"],
                        "login_return_path_shape": returned["path_shape"],
                    }
                )
            item["failure"] = failure_summary
        sources.append(item)
    integrity = _mapping(artifact["integrity"], "sealed integrity")
    release_binding = _mapping(artifact["release_binding"], "sealed release binding")
    provider_count = _integer(
        assessment["exact_all_in_lodging_provider_count"],
        "sealed assessment.exact_all_in_lodging_provider_count",
    )
    summary: dict[str, object] = {
        "schema_version": "tripchord-live-browser-focused-run-summary-v2",
        "captured_at": artifact["evidence_closed_at"],
        "scope": artifact["scope"],
        "query": artifact["query"],
        "runtime": {
            "model_provider": runtime["model_provider"],
            "primary_model": runtime["primary_model"],
            "model_required": runtime["model_required"],
            "companion_manifest_version": identity["manifest_version"],
            "companion_content_runtime_version": identity["content_runtime_version"],
            "companion_build_sha256": identity["build_sha256"],
            "companion_runtime_instance_id": companion["runtime_instance_id"],
            "background_reload_verified": True,
            "browser_focused": False,
            "current_worktree_matches_captured_build": release_binding[
                "current_worktree_matches_captured_build"
            ],
        },
        "sources": sources,
        "scope_decisions": artifact["scope_decisions"],
        "assessment": {
            "exact_all_in_lodging_provider_count": provider_count,
            "one_provider_exact_lodging_quote": provider_count == 1,
            "two_provider_exact_lodging_quote": provider_count >= 2,
            "strict_lodging_gate_passed": assessment["strict_lodging_gate_passed"],
            "publication_gate_attempted": assessment["publication_gate_attempted"],
            "publication_gate_passed": assessment["publication_gate_passed"],
        },
        "sealed_evidence": {
            "path": sealed_artifact_name,
            "input_sha256": integrity["input_sha256"],
            "result_sha256": integrity["result_sha256"],
            "source_artifact_count": len(
                _sequence(artifact["source_artifacts"], "sealed source artifacts")
            ),
        },
        "claim_boundary": artifact["claim_boundary"],
    }
    summary["result_sha256"] = _canonical_sha256(summary)
    _assert_public_safe(summary)
    return summary


def _atomic_write_json(
    path: Path,
    payload: Mapping[str, object],
    *,
    mode: int = 0o600,
) -> None:
    if mode not in {0o600, 0o644}:
        raise EvidenceCaptureError("evidence output mode is outside the fixed allowlist")
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() or path.is_symlink():
        raise EvidenceCaptureError("refusing to overwrite an existing evidence artifact")
    temporary = path.parent / f".{path.name}.tmp-{os.getpid()}-{secrets.token_hex(8)}"
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    descriptor = -1
    try:
        descriptor = os.open(temporary, flags, mode)
        os.fchmod(descriptor, mode)
        with os.fdopen(descriptor, "wb") as stream:
            descriptor = -1
            stream.write(json.dumps(payload, ensure_ascii=False, indent=2).encode("utf-8"))
            stream.write(b"\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temporary, path, follow_symlinks=False)
        temporary.unlink()
        _fsync_directory(path.parent)
    except FileExistsError as exc:
        raise EvidenceCaptureError("refusing to overwrite an existing evidence artifact") from exc
    except OSError as exc:
        raise EvidenceCaptureError(f"cannot atomically write evidence artifact: {path}") from exc
    finally:
        if descriptor >= 0:
            os.close(descriptor)
        temporary.unlink(missing_ok=True)


def _load_json(path: Path, label: str) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise EvidenceCaptureError(f"cannot read {label}: {path}") from exc
    if not isinstance(payload, dict):
        raise EvidenceCaptureError(f"{label} must be a JSON object")
    return payload


def capture_from_runtime(
    *,
    repository: Path,
    base_url: str,
    bridge_token_file: Path,
    task_ids: Sequence[str],
    companion_id: str | None,
    source_summary_path: Path | None,
    skipped_lodging_providers: Sequence[str] = (),
) -> dict[str, object]:
    base = _validate_base_url(base_url)
    token = _secure_token(bridge_token_file)
    if len(task_ids) < 2 or any(not _TASK_ID.fullmatch(task_id) for task_id in task_ids):
        raise EvidenceCaptureError("at least two valid --task-id values are required")
    with httpx.Client(
        base_url=base,
        follow_redirects=False,
        timeout=10.0,
        trust_env=False,
    ) as client:
        task_payloads = [
            _fetch_json(
                client,
                f"/browser-bridge/v1/tasks/{quote(task_id, safe='')}",
                bridge_token=token,
            )
            for task_id in task_ids
        ]
        companion_payload = _fetch_json(
            client,
            "/browser-bridge/v1/companions/status",
            bridge_token=token,
        )
        runtime_payload = _fetch_json(client, "/api/v1/agents/runtime")
    source_summary = (
        _load_json(source_summary_path, "source summary")
        if source_summary_path is not None
        else None
    )
    release_binding = _release_binding(repository)
    source_artifacts = _source_artifact_receipts(repository, source_summary_path)
    if _release_binding(repository) != release_binding:
        raise EvidenceCaptureError("Companion source changed during evidence capture")
    if _source_artifact_receipts(repository, source_summary_path) != source_artifacts:
        raise EvidenceCaptureError("source artifacts changed during evidence capture")
    if (
        source_summary_path is not None
        and _load_json(source_summary_path, "source summary") != source_summary
    ):
        raise EvidenceCaptureError("source summary changed during evidence capture")
    return build_sealed_evidence(
        task_payloads=task_payloads,
        task_ids=task_ids,
        companion_payload=companion_payload,
        companion_id=companion_id,
        runtime_payload=runtime_payload,
        source_summary=source_summary,
        source_artifacts=source_artifacts,
        release_binding=release_binding,
        scope_decisions=[
            {
                "provider": provider,
                "vertical": "lodging",
                "state": "skipped_by_user",
                "coverage_credit": False,
            }
            for provider in skipped_lodging_providers
        ],
    )


def main() -> int:
    args = _arguments()
    try:
        repository = args.repository.resolve()
        if args.verify is not None:
            verify_stat = args.verify.lstat()
            if (
                stat.S_ISLNK(verify_stat.st_mode)
                or not stat.S_ISREG(verify_stat.st_mode)
                or stat.S_IMODE(verify_stat.st_mode) != 0o600
            ):
                raise EvidenceCaptureError("sealed evidence must be a regular mode-0600 file")
            artifact = _load_json(args.verify, "sealed evidence")
            verify_sealed_evidence(artifact)
            if args.summary_output is not None:
                _atomic_write_json(
                    args.summary_output,
                    build_run_summary(
                        artifact,
                        sealed_artifact_name=args.verify.name,
                    ),
                    mode=0o644,
                )
            print(f"verified {args.verify}")
            return 0
        required = {
            "--bridge-token-file": args.bridge_token_file,
            "--output": args.output,
        }
        missing = [name for name, value in required.items() if value is None]
        if missing:
            raise EvidenceCaptureError(f"capture mode requires: {', '.join(missing)}")
        artifact = capture_from_runtime(
            repository=repository,
            base_url=args.base_url,
            bridge_token_file=args.bridge_token_file,
            task_ids=args.task_id,
            companion_id=args.companion_id,
            source_summary_path=args.source_summary,
            skipped_lodging_providers=args.skipped_lodging_provider,
        )
        _atomic_write_json(args.output, artifact)
        verify_sealed_evidence(_load_json(args.output, "sealed evidence"))
        if stat.S_IMODE(args.output.lstat().st_mode) != 0o600:
            raise EvidenceCaptureError("sealed evidence mode is not 0600")
        if args.summary_output is not None:
            _atomic_write_json(
                args.summary_output,
                build_run_summary(
                    artifact,
                    sealed_artifact_name=args.output.name,
                ),
                mode=0o644,
            )
        print(f"sealed {args.output}")
        return 0
    except EvidenceCaptureError as exc:
        print(f"evidence capture failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
