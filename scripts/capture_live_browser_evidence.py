def _source_artifact_receipts(
    repository: Path,
    source_summary: Path | None,
) -> list[dict[str, str]]:
    resolved_repository = repository.resolve()
    try:
        from tripchord.agents.companion_control_tools import (
            COMPANION_BUILD_FILE_ALLOWLIST,
        )
    except ImportError:
        api_source = repository / "apps" / "api" / "src"
        if str(api_source) not in sys.path:
            sys.path.insert(0, str(api_source))
        from tripchord.agents.companion_control_tools import (
            COMPANION_BUILD_FILE_ALLOWLIST,
        )
    relative_paths = {
        *_SOURCE_ARTIFACTS,
        *(f"apps/browser-companion/{item}" for item in COMPANION_BUILD_FILE_ALLOWLIST),
    }
    paths = [repository / item for item in sorted(relative_paths)]
    if source_summary is not None:
        paths.append(source_summary)
    receipts: list[dict[str, str]] = []
    for path in paths:
        if path.is_symlink() or not path.is_file():
            raise EvidenceCaptureError(f"source artifact is not a regular file: {path}")
        resolved = path.resolve()
        if not resolved.is_relative_to(resolved_repository):
            raise EvidenceCaptureError(f"source artifact is outside the repository: {path}")
        receipts.append(
            {
                "path": resolved.relative_to(resolved_repository).as_posix(),
                "sha256": _file_sha256(resolved),
            }
        )
    receipts.sort(key=lambda item: item["path"])
    return receipts


def _release_binding(repository: Path) -> dict[str, object]:
    api_source = repository / "apps" / "api" / "src"
    if str(api_source) not in sys.path:
        sys.path.insert(0, str(api_source))
    try:
        from pydantic import ValidationError
        from tripchord.agents.companion_control_tools import (
            BrowserCompanionReleaseSeal,
            companion_build_sha256,
        )
        from tripchord.providers.browser_bridge import BrowserCompanionBuildIdentity
    except ImportError as exc:
        raise EvidenceCaptureError("cannot import the Companion release schemas") from exc
    companion_directory = repository / "apps" / "browser-companion"
    seal_path = companion_directory / ".tripchord-release-seal.json"
    meta_path = companion_directory / "src" / "build-meta.js"
    for path, label in ((seal_path, "release seal"), (meta_path, "build metadata")):
        try:
            file_stat = path.lstat()
        except FileNotFoundError as exc:
            raise EvidenceCaptureError(f"Companion {label} is missing") from exc
        if stat.S_ISLNK(file_stat.st_mode) or not stat.S_ISREG(file_stat.st_mode):
            raise EvidenceCaptureError(f"Companion {label} must be a regular file")
    seal_stat = seal_path.stat()
    if seal_stat.st_uid != os.getuid() or stat.S_IMODE(seal_stat.st_mode) != 0o600:
        raise EvidenceCaptureError("historical release seal must be current-user 0600")
    try:
        seal = BrowserCompanionReleaseSeal.model_validate_json(seal_path.read_bytes())
        meta_bytes = meta_path.read_bytes()
        match = _BUILD_META_PATTERN.fullmatch(meta_bytes.decode("utf-8"))
        if match is None:
            raise EvidenceCaptureError("historical build metadata is not canonical")
        identity = BrowserCompanionBuildIdentity.model_validate_json(match.group("payload"))
    except (UnicodeError, ValidationError) as exc:
        raise EvidenceCaptureError("historical Companion release receipt is invalid") from exc
    if _file_sha256(meta_path) != seal.build_meta_sha256:
        raise EvidenceCaptureError("historical release seal no longer binds build metadata")
    sealed_identity = {
        "protocol_version": seal.protocol_version,
        "manifest_version": seal.manifest_version,
        "build_sha256": seal.build_sha256,
        "content_runtime_version": seal.content_runtime_version,
    }
    if identity.model_dump(mode="json") != sealed_identity:
        raise EvidenceCaptureError("historical release seal and build metadata disagree")
    try:
        current_worktree_build_sha256 = companion_build_sha256(companion_directory)
    except (OSError, RuntimeError) as exc:
        raise EvidenceCaptureError("cannot hash the current Companion worktree") from exc
    return {
        "sealed_identity": sealed_identity,
        "release_seal_sha256": _file_sha256(seal_path),
        "build_meta_sha256": _file_sha256(meta_path),
        "current_worktree_build_sha256": current_worktree_build_sha256,
        "current_worktree_matches_captured_build": (
            current_worktree_build_sha256 == seal.build_sha256
        ),
        "boundary": (
            "The current source bytes exactly match the release-sealed build identity."
            if current_worktree_build_sha256 == seal.build_sha256
            else (
                "The release seal and build-meta retain the build loaded for the terminal "
                "tasks. The current worktree changed after that run; its separately recorded "
                "build hash is not substituted for the captured Companion identity."
            )
        ),
    }


def _lowest_rate(quotes: Sequence[Mapping[str, object]]) -> dict[str, object] | None:
    if not quotes:
        return None
    selected = min(
        quotes,
        key=lambda item: (Decimal(str(item["amount"])), str(item["evidence_sha256"])),
    )
    return {
        "amount": selected["amount"],
        "currency": selected["currency"],
        "price_basis": selected["price_basis"],
        "taxes_included": selected["taxes_included"],
        "price_finality": selected["price_finality"],
        "property": selected["property"],
        "evidence_sha256": selected["evidence_sha256"],
    }


def _derive_assessment(
    sources: Sequence[Mapping[str, object]],
    *,
    publication_gate_attempted: bool,
    publication_gate_passed: bool,
) -> dict[str, object]:
    exact_provider_quotes: dict[str, list[Mapping[str, object]]] = {}
    quote_count_by_provider: dict[str, int] = {}
    terminal_state_by_provider: dict[str, str] = {}
    for source in sources:
        provider = str(source["provider"])
        quotes = [
            _mapping(item, "sealed quote")
            for item in _sequence(source.get("quotes", []), "sealed source.quotes")
        ]
        quote_count_by_provider[provider] = len(quotes)
        terminal_state_by_provider[provider] = str(source["state"])
        exact = [
            item
            for item in quotes
            if item.get("taxes_included") is True
            and item.get("price_finality") == "final_for_rate"
            and item.get("price_basis") in {"per_night", "total_stay"}
            and isinstance(item.get("property"), Mapping)
        ]
        if exact:
            exact_provider_quotes[provider] = exact
    exact_providers = sorted(exact_provider_quotes)
    return {
        "quote_count_by_provider": dict(sorted(quote_count_by_provider.items())),
        "terminal_state_by_provider": dict(sorted(terminal_state_by_provider.items())),
        "exact_all_in_lodging_providers": exact_providers,
        "exact_all_in_lodging_provider_count": len(exact_providers),
        "lowest_exact_all_in_rate_by_provider": {
            provider: _lowest_rate(exact_provider_quotes[provider])
            for provider in exact_providers
        },
        "strict_lodging_provider_threshold": 2,
        "strict_lodging_gate_passed": len(exact_providers) >= 2,
        "publication_gate_attempted": publication_gate_attempted,
        "publication_gate_passed": publication_gate_passed,
    }


def _summary_scope_decisions(summary: Mapping[str, Any]) -> list[dict[str, object]]:
    decisions: list[dict[str, object]] = []
    for item in _sequence(summary.get("sources", []), "source summary.sources"):
        source = _mapping(item, "source summary source")
        if "task_id" in source:
            continue
        decisions.append(
            {
                "provider": _string(source.get("provider"), "scope provider", maximum=32),
                "vertical": _string(source.get("vertical"), "scope vertical", maximum=32),
                "state": _string(source.get("state"), "scope state", maximum=64),
                "coverage_credit": _boolean(
                    source.get("coverage_credit"), "scope coverage_credit"
                ),
            }
        )
    decisions.sort(key=lambda item: (str(item["provider"]), str(item["vertical"])))
    return decisions


def _normalize_scope_decisions(
    raw: Sequence[Mapping[str, object]],
) -> list[dict[str, object]]:
    decisions: list[dict[str, object]] = []
    seen: set[tuple[str, str]] = set()
    for index, item in enumerate(raw):
        provider = _string(item.get("provider"), f"scope_decisions[{index}].provider")
        vertical = _string(item.get("vertical"), f"scope_decisions[{index}].vertical")
        state = _string(item.get("state"), f"scope_decisions[{index}].state")
        coverage_credit = _boolean(
            item.get("coverage_credit"), f"scope_decisions[{index}].coverage_credit"
        )
        if provider not in _PROVIDER_DOMAINS:
            raise EvidenceCaptureError("scope decision provider is outside the allowlist")
        if vertical != "lodging" or state != "skipped_by_user" or coverage_credit is not False:
            raise EvidenceCaptureError(
                "focused scope decisions may only record skipped lodging with no coverage"
            )
        key = (provider, vertical)
        if key in seen:
            raise EvidenceCaptureError("focused scope decisions must be unique")
        seen.add(key)
        decisions.append(
            {
                "provider": provider,
                "vertical": vertical,
                "state": state,
                "coverage_credit": coverage_credit,
            }
        )
    decisions.sort(key=lambda item: (str(item["provider"]), str(item["vertical"])))
    return decisions


def _validate_source_summary(
    summary: Mapping[str, Any],
    sources: Sequence[Mapping[str, object]],
    query: Mapping[str, object],
    companion: Mapping[str, object],
    runtime: Mapping[str, object],
    assessment: Mapping[str, object],
) -> None:
    if summary.get("schema_version") != "tripchord-live-browser-focused-evidence-v1":
        raise EvidenceCaptureError("source summary has an unexpected schema version")
    summary_query = dict(_mapping(summary.get("query"), "source summary.query"))
    expected_summary_query = {
        key: value for key, value in query.items() if key != "recent_quote_reuse_allowed"
    }
    if summary_query != expected_summary_query:
        raise EvidenceCaptureError("source summary query does not match terminal tasks")
    summary_sources = {
        str(item.get("task_id")): item
        for raw in _sequence(summary.get("sources", []), "source summary.sources")
        if (item := _mapping(raw, "source summary source")).get("task_id") is not None
    }
    for source in sources:
        task_id = str(source["task_id"])
        old = _mapping(summary_sources.get(task_id), f"source summary[{task_id}]")
        for field in ("provider", "state", "attempt_count", "quote_count"):
            if old.get(field) != source.get(field):
                raise EvidenceCaptureError(f"source summary {task_id}.{field} is inconsistent")
        if source["quote_count"]:
            quotes = [
                _mapping(item, "sealed quote")
                for item in _sequence(source["quotes"], "sealed quotes")
            ]
            lowest = _lowest_rate(quotes)
            old_lowest = _mapping(old.get("lowest_audited_rate"), "source summary lowest rate")
            if lowest is None:
                raise EvidenceCaptureError("source summary expected a lowest quote")
            old_property = {
                "id": old_lowest.get("property_id"),
                "name": old_lowest.get("property_name"),
            }
            for field in (
                "amount",
                "currency",
                "price_basis",
                "taxes_included",
                "evidence_sha256",
            ):
                if old_lowest.get(field) != lowest.get(field):
                    raise EvidenceCaptureError(
                        f"source summary lowest rate {field} is inconsistent"
                    )
            if old_property != lowest["property"]:
                raise EvidenceCaptureError("source summary lowest property is inconsistent")
    summary_runtime = _mapping(summary.get("runtime"), "source summary.runtime")
    build_identity = _mapping(companion["build_identity"], "companion build identity")
    expected_runtime = {
        "model_provider": runtime["model_provider"],
        "primary_model": runtime["primary_model"],
        "model_required": runtime["model_required"],
        "companion_manifest_version": build_identity["manifest_version"],
        "companion_content_runtime_version": build_identity["content_runtime_version"],
        "companion_build_sha256": build_identity["build_sha256"],
        "companion_runtime_instance_id": companion["runtime_instance_id"],
        "background_reload_verified": True,
        "browser_focused": False,
    }
    if dict(summary_runtime) != expected_runtime:
        raise EvidenceCaptureError("source summary runtime identity is inconsistent")
    old_assessment = _mapping(summary.get("assessment"), "source summary.assessment")
    for field in (
        "strict_lodging_gate_passed",
        "publication_gate_attempted",
        "publication_gate_passed",
    ):
        if old_assessment.get(field) != assessment.get(field):
            raise EvidenceCaptureError(f"source summary assessment.{field} is inconsistent")


def _validate_runtime_binding(
    sources: Sequence[Mapping[str, object]],
    companion: Mapping[str, object],
    runtime: Mapping[str, object],
    release_binding: Mapping[str, object],
) -> None:
    if runtime["model_enabled"] is not True or runtime["model_required"] is not True:
        raise EvidenceCaptureError("focused required-model evidence needs the strict model runtime")
    if (
        runtime["codex_runtime_dependency"] is not False
        or runtime["chatgpt_runtime_dependency"] is not False
    ):
        raise EvidenceCaptureError("runtime dependency boundary is not independent")
    if (
        runtime["browser_companion_auto_reload_enabled"] is not True
        or runtime["browser_companion_supervisor_running"] is not True
    ):
        raise EvidenceCaptureError("Browser Companion background reload runtime is not enabled")
    build_identity = _mapping(companion["build_identity"], "companion.build_identity")
    sealed_identity = _mapping(
        release_binding.get("sealed_identity"), "release binding.sealed_identity"
    )
    if dict(build_identity) != dict(sealed_identity):
        raise EvidenceCaptureError(
            "live Companion identity does not match the retained release receipt"
        )
    source_providers = {str(source["provider"]) for source in sources}
    companion_providers = {
        str(item)
        for item in _sequence(companion["providers"], "companion.providers")
    }
    if not source_providers.issubset(companion_providers):
        raise EvidenceCaptureError("live Companion provider capabilities do not cover the tasks")
    receipt = _mapping(
        runtime["browser_companion_last_reconcile"], "runtime.last_reconcile"
    )
    if receipt.get("state") != "applied":
        raise EvidenceCaptureError("focused evidence requires the applied reload receipt")
    if (
        receipt.get("companion_id") != companion["companion_id"]
        or receipt.get("target_build_sha256") != build_identity["build_sha256"]
        or receipt.get("new_runtime_instance_id") != companion["runtime_instance_id"]
    ):
        raise EvidenceCaptureError("reload receipt does not bind the current Companion runtime")


def _assert_public_safe(value: object, *, path: str = "artifact") -> None:
    if isinstance(value, Mapping):
        for key, item in value.items():
            normalized_key = str(key).lower()
            if any(forbidden in normalized_key for forbidden in _FORBIDDEN_OUTPUT_KEYS):
                raise EvidenceCaptureError(f"sealed output contains forbidden field {path}.{key}")
            _assert_public_safe(item, path=f"{path}.{key}")
        return
    if isinstance(value, list | tuple):
        for index, item in enumerate(value):
            _assert_public_safe(item, path=f"{path}[{index}]")
        return
    if isinstance(value, str):
        if re.search(r"\bsk-[A-Za-z0-9_-]{16,}\b", value):
            raise EvidenceCaptureError(f"sealed output contains an API-key-shaped value at {path}")
        maximum = 4096 if path.endswith("page_url") else 1024
        if len(value) > maximum:
            raise EvidenceCaptureError(f"sealed output contains an overlong string at {path}")


