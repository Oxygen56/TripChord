import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const companionRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BUILD_META_PATH = "src/build-meta.js";
const BUILD_ALLOWLIST = Object.freeze([
  "manifest.json",
  "popup.html",
  "popup.css",
  "popup.js",
  "offscreen.html",
  "src/background.js",
  "src/content.js",
  "src/offscreen.js",
  "src/parser.js",
]);
const CONTROL_PROTOCOL_VERSION = "tripchord-companion-control-v1";

function canonicalBuildChunk(relativePath, content) {
  return [
    Buffer.from(`${relativePath}\0${content.byteLength}\0`, "utf8"),
    content,
    Buffer.from("\0", "utf8"),
  ];
}

async function buildIdentity() {
  const manifest = JSON.parse(
    await readFile(resolve(companionRoot, "manifest.json"), "utf8"),
  );
  const background = await readFile(
    resolve(companionRoot, "src/background.js"),
    "utf8",
  );
  const runtimeMatch = background.match(
    /const CONTENT_RUNTIME_VERSION = "([A-Za-z0-9][A-Za-z0-9._+-]*)";/,
  );
  if (!runtimeMatch) {
    throw new Error("background.js must declare CONTENT_RUNTIME_VERSION");
  }
  const digest = createHash("sha256");
  for (const relativePath of BUILD_ALLOWLIST) {
    const content = await readFile(resolve(companionRoot, relativePath));
    for (const chunk of canonicalBuildChunk(relativePath, content)) {
      digest.update(chunk);
    }
  }
  return {
    protocol_version: CONTROL_PROTOCOL_VERSION,
    manifest_version: String(manifest.version),
    build_sha256: digest.digest("hex"),
    content_runtime_version: runtimeMatch[1],
  };
}

const identity = await buildIdentity();
const source = [
  "// Generated by scripts/update-build-meta.mjs. Do not edit by hand.",
  `globalThis.TRIPCHORD_COMPANION_BUILD_META = Object.freeze(${JSON.stringify(identity, null, 2)});`,
  "",
].join("\n");
await writeFile(resolve(companionRoot, BUILD_META_PATH), source, "utf8");
process.stdout.write(`${identity.build_sha256}\n`);

export { BUILD_ALLOWLIST, canonicalBuildChunk };
