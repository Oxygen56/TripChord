@pytest.mark.asyncio
async def test_tool_verifies_build_requests_reload_and_returns_sanitized_receipt(
    tmp_path: Path,
) -> None:
    target = _write_companion_build(tmp_path)
    queued = _snapshot(target.build_sha256, BrowserCompanionControlState.QUEUED)
    applied = _snapshot(
        target.build_sha256,
        BrowserCompanionControlState.APPLIED,
        observed_build_sha256=target.build_sha256,
        observed_runtime_instance_id=NEW_RUNTIME_INSTANCE_ID,
    )
    bridge = _FakeBridge(_status(), queued, (applied,))

    async def no_wait(_: float) -> None:
        return None

    registry = ToolRegistry()
    CompanionControlTools(
        bridge,
        companion_directory=tmp_path,
        poll_interval_seconds=0.001,
        wait_timeout_seconds=15,
        now=lambda: NOW,
        sleep=no_wait,
    ).register(registry)
    receipt = await registry.invoke(_call(reason_code="companion_build_changed"))

    assert len(bridge.requests) == 1
    companion_id, idempotency_key, request = bridge.requests[0]
    assert companion_id == COMPANION_ID
    assert idempotency_key.startswith("agent-reload-")
    assert request.expected_current_build_sha256 == OLD_BUILD_SHA256
    assert request.target_build_sha256 == target.build_sha256
    assert request.reason_code == BrowserCompanionReloadReasonCode.COMPANION_BUILD_CHANGED
    assert receipt.output == {
        "request_id": "companion-reload-fixture-request",
        "companion_id": COMPANION_ID,
        "state": "applied",
        "old_build_sha256": OLD_BUILD_SHA256,
        "target_build_sha256": target.build_sha256,
        "old_runtime_instance_id": OLD_RUNTIME_INSTANCE_ID,
        "new_runtime_instance_id": NEW_RUNTIME_INSTANCE_ID,
        "timings": {
            "requested_at": NOW.isoformat(),
            "updated_at": (NOW + timedelta(seconds=1)).isoformat(),
            "accepted_at": NOW.isoformat(),
            "applied_at": (NOW + timedelta(seconds=1)).isoformat(),
            "elapsed_ms": 1000,
        },
    }
    assert not any(
        forbidden in json.dumps(receipt.output).lower()
        for forbidden in ("bridge_token", "control_token", "http://", "https://", "script_path")
    )


