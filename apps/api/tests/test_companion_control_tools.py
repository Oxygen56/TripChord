    CompanionControlTools(bridge, companion_directory=tmp_path).register(registry)

    spec = registry.spec(RELOAD_VERIFIED_COMPANION_TOOL)
    assert spec.permission == ToolPermission.REVERSIBLE_WRITE
    assert spec.allowed_roles == (AgentRole.EXECUTOR,)
    assert spec.input_schema == {
        "type": "object",
        "properties": {
            "reason_code": {
                "type": "string",
                "enum": [reason.value for reason in BrowserCompanionReloadReasonCode],
            }
        },
        "required": ["reason_code"],
        "additionalProperties": False,
    }
    serialized = json.dumps(spec.input_schema)
    for forbidden in ("build_sha256", "url", "script", "token", "path"):
        assert forbidden not in serialized.lower()


