def _canonical_build_sha256(root: Path) -> str:
    digest = hashlib.sha256()
    for relative_path in COMPANION_BUILD_FILE_ALLOWLIST:
        payload = (root / relative_path).read_bytes()
        digest.update(relative_path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(str(len(payload)).encode("ascii"))
        digest.update(b"\0")
        digest.update(payload)
        digest.update(b"\0")
    return digest.hexdigest()


def _write_companion_build(root: Path) -> BrowserCompanionBuildIdentity:
    for relative_path in COMPANION_BUILD_FILE_ALLOWLIST:
        path = root / relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        if relative_path == "manifest.json":
            path.write_text(
                json.dumps({"manifest_version": 3, "version": "0.1.1"}),
                encoding="utf-8",
            )
        elif relative_path == "src/background.js":
            path.write_text(
                'const CONTENT_RUNTIME_VERSION = "2026-08-04.1";\n',
                encoding="utf-8",
            )
        else:
            path.write_bytes(f"fixture:{relative_path}\n".encode())
    identity = BrowserCompanionBuildIdentity(
        manifest_version="0.1.1",
        build_sha256=_canonical_build_sha256(root),
        content_runtime_version="2026-08-04.1",
    )
    meta = root / "src" / "build-meta.js"
    payload = json.dumps(identity.model_dump(mode="json"), ensure_ascii=False, indent=2)
    meta.write_text(
        "// Generated by scripts/update-build-meta.mjs. Do not edit by hand.\n"
        "globalThis.TRIPCHORD_COMPANION_BUILD_META = "
        f"Object.freeze({payload});\n",
        encoding="utf-8",
    )
    seal_path = root / COMPANION_RELEASE_SEAL_RELATIVE_PATH
    seal_path.write_bytes(companion_release_seal_bytes(root))
    seal_path.chmod(0o600)
    return identity


def _status(
    *,
    build_sha256: str = OLD_BUILD_SHA256,
    runtime_instance_id: str = OLD_RUNTIME_INSTANCE_ID,
    is_fresh: bool = True,
    companion_id: str = COMPANION_ID,
    protocol_version: str = COMPANION_CONTROL_PROTOCOL_VERSION,
) -> BrowserCompanionStatusResponse:
    build = BrowserCompanionBuildIdentity(
        protocol_version=protocol_version,
        manifest_version="0.1.0",
        build_sha256=build_sha256,
        content_runtime_version="2026-08-03.1",
    )
    return BrowserCompanionStatusResponse(
        status="connected" if is_fresh else "disconnected",
        server_time=NOW,
        stale_after_seconds=45,
        companions=(
            BrowserCompanionHeartbeat(
                companion_id=companion_id,
                providers=(
                    BrowserProvider.CTRIP,
                    BrowserProvider.QUNAR,
                    BrowserProvider.TONGCHENG,
                ),
                last_seen=NOW,
                age_seconds=0 if is_fresh else 46,
                is_fresh=is_fresh,
                build_identity=build,
                runtime_instance_id=runtime_instance_id,
            ),
        ),
    )


def _snapshot(
    target_sha256: str,
    state: BrowserCompanionControlState,
    *,
    companion_id: str = COMPANION_ID,
    observed_build_sha256: str | None = None,
    observed_runtime_instance_id: str | None = None,
    failure_code: str | None = None,
) -> BrowserCompanionReloadRequestSnapshot:
    applied_at = (
        NOW + timedelta(seconds=1) if state == BrowserCompanionControlState.APPLIED else None
    )
    return BrowserCompanionReloadRequestSnapshot(
        id="companion-reload-fixture-request",
        kind=BrowserCompanionControlKind.RELOAD_EXTENSION,
        companion_id=companion_id,
        idempotency_key="agent-reload-" + "1" * 64,
        expected_current_build_sha256=OLD_BUILD_SHA256,
        target_build_sha256=target_sha256,
        reason_code=BrowserCompanionReloadReasonCode.COMPANION_BUILD_CHANGED,
        state=state,
        requested_at=NOW,
        updated_at=applied_at or NOW,
        expires_at=NOW + timedelta(seconds=120),
        drain_deadline_at=NOW + timedelta(seconds=120),
        delivery_generation=1 if state != BrowserCompanionControlState.QUEUED else 0,
        expected_runtime_instance_id=OLD_RUNTIME_INSTANCE_ID,
        accepted_at=NOW if state == BrowserCompanionControlState.APPLIED else None,
        applied_at=applied_at,
        observed_build_sha256=observed_build_sha256,
        observed_runtime_instance_id=observed_runtime_instance_id,
        failure_code=failure_code,
    )


class _FakeBridge:
    def __init__(
        self,
        status: BrowserCompanionStatusResponse,
        initial: BrowserCompanionReloadRequestSnapshot | None = None,
        polls: tuple[BrowserCompanionReloadRequestSnapshot, ...] = (),
    ) -> None:
        self.status = status
        self.initial = initial
        self.polls = deque(polls)
        self.requests: list[tuple[str, str, BrowserCompanionReloadRequestBody]] = []
        self.status_calls = 0

    async def companion_status(self) -> BrowserCompanionStatusResponse:
        self.status_calls += 1
        return self.status

    async def request_reload(
        self,
        companion_id: str,
        *,
        idempotency_key: str,
        request: BrowserCompanionReloadRequestBody,
    ) -> BrowserCompanionReloadRequestSnapshot:
        self.requests.append((companion_id, idempotency_key, request))
        if self.initial is None:
            raise AssertionError("unexpected reload request")
        return self.initial

    async def get_reload_request(
        self,
        companion_id: str,
        request_id: str,
    ) -> BrowserCompanionReloadRequestSnapshot:
        assert companion_id == COMPANION_ID
        assert request_id == "companion-reload-fixture-request"
        if not self.polls:
            assert self.initial is not None
            return self.initial
        return self.polls.popleft()


