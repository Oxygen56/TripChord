    (tmp_path / COMPANION_RELEASE_SEAL_RELATIVE_PATH).write_bytes(stale_seal)
    (tmp_path / COMPANION_RELEASE_SEAL_RELATIVE_PATH).chmod(0o600)

    with pytest.raises(CompanionControlToolError, match="exact manifest/runtime/build"):
        verified_companion_build_identity(tmp_path)


