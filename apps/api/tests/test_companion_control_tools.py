def test_verified_identity_requires_exact_canonical_release_seal(tmp_path: Path) -> None:
    identity = _write_companion_build(tmp_path)
    seal_path = tmp_path / COMPANION_RELEASE_SEAL_RELATIVE_PATH
    original_seal = seal_path.read_bytes()

    seal_path.unlink()
    with pytest.raises(CompanionControlToolError, match="release seal"):
        verified_companion_build_identity(tmp_path)

    seal_path.write_bytes(original_seal.replace(identity.build_sha256.encode(), b"f" * 64))
    seal_path.chmod(0o600)
    with pytest.raises(CompanionControlToolError, match="release seal"):
        verified_companion_build_identity(tmp_path)

    seal_path.write_bytes(original_seal.rstrip() + b" \n")
    seal_path.chmod(0o600)
    with pytest.raises(CompanionControlToolError, match="exact manifest/runtime/build"):
        verified_companion_build_identity(tmp_path)

    seal_path.write_bytes(original_seal)
    seal_path.chmod(0o644)
    with pytest.raises(CompanionControlToolError, match="exact mode 0600"):
        verified_companion_build_identity(tmp_path)


def test_verified_identity_rejects_stale_seal_for_new_valid_metadata(tmp_path: Path) -> None:
    old_identity = _write_companion_build(tmp_path)
    stale_seal = (tmp_path / COMPANION_RELEASE_SEAL_RELATIVE_PATH).read_bytes()
